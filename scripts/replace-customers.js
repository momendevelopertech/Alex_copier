async function main() {
  console.log("Deleting all existing customer-related data...");

  // Delete in order of dependencies
  await prisma.customerPayment.deleteMany();
  await prisma.customerLedger.deleteMany();
  await prisma.customerLocation.deleteMany();

  // Check for linked records
  const linkedCounts = await Promise.all([
    prisma.salesOrder.count(),
    prisma.serviceRequest.count(),
    prisma.contract.count(),
    prisma.settlement.count(),
    prisma.machine.count({ where: { currentOwnerId: { not: null } } }),
  ]);

  const hasLinkedData = linkedCounts.some((c) => c > 0);
  if (hasLinkedData) {
    console.log("WARNING: There are linked records (orders, contracts, etc.).");
    console.log("Sales orders:", linkedCounts[0]);
    console.log("Service requests:", linkedCounts[1]);
    console.log("Contracts:", linkedCounts[2]);
    console.log("Settlements:", linkedCounts[3]);
    console.log("Machines with owners:", linkedCounts[4]);
    console.log("");
    console.log("Deleting customers anyway (linked records will keep their customerId references)...");
  }

  await prisma.customer.deleteMany();
  console.log("All customers deleted.");

  console.log(`Creating ${CUSTOMER_NAMES.length} new customers...`);

  // Create in batches of 50
  const BATCH_SIZE = 50;
  for (let i = 0; i < CUSTOMER_NAMES.length; i += BATCH_SIZE) {
    const batch = CUSTOMER_NAMES.slice(i, i + BATCH_SIZE);
    await prisma.customer.createMany({
      data: batch.map((name) => ({ name })),
      skipDuplicates: true,
    });
    console.log(`  Created ${Math.min(i + BATCH_SIZE, CUSTOMER_NAMES.length)} / ${CUSTOMER_NAMES.length}`);
  }

  const total = await prisma.customer.count();
  console.log(`Done! Total customers in database: ${total}`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
